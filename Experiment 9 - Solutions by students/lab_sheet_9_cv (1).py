from ultralytics import YOLO
from google.colab import files

import cv2
import matplotlib.pyplot as plt
import numpy as np


# ============================================================
# STEP 3: UPLOAD YOUR IMAGE
# ============================================================

print("Please upload an image for object detection.")

uploaded = files.upload()

image_path = list(uploaded.keys())[0]

print("\nImage uploaded successfully:")
print(image_path)


# ============================================================
# STEP 4: LOAD PRE-TRAINED YOLOv8 MODEL
# ============================================================

model = YOLO("yolov8n.pt")

print("\nYOLOv8 model loaded successfully!")


# ============================================================
# STEP 5: PERFORM OBJECT DETECTION
# ============================================================

results = model(image_path)

result = results[0]

print("\nObject detection completed successfully!")


# ============================================================
# STEP 6: DISPLAY DETECTED OBJECTS
# ============================================================

print("\nDetected Objects:")
print("---------------------------")

for box in result.boxes:

    class_id = int(box.cls[0])

    class_name = model.names[class_id]

    confidence = float(box.conf[0])

    print(
        f"Object: {class_name} | "
        f"Confidence: {confidence:.2f}"
    )


# ============================================================
# STEP 7: DISPLAY IMAGE WITH BOUNDING BOXES
# ============================================================

annotated_image = result.plot()

# Convert BGR to RGB
annotated_image = cv2.cvtColor(
    annotated_image,
    cv2.COLOR_BGR2RGB
)

plt.figure(figsize=(12, 8))

plt.imshow(annotated_image)

plt.axis("off")

plt.title("YOLOv8 Object Detection")

plt.show()


# ============================================================
# STEP 8: DISPLAY BOUNDING BOX COORDINATES
# ============================================================

print("\nBounding Box Information:")
print("---------------------------")

for box in result.boxes:

    class_id = int(box.cls[0])

    class_name = model.names[class_id]

    confidence = float(box.conf[0])

    coordinates = box.xyxy[0].tolist()

    print(
        f"Object: {class_name}"
    )

    print(
        f"Confidence: {confidence:.2f}"
    )

    print(
        f"Bounding Box: {coordinates}"
    )

    print("---------------------------")


# ============================================================
# STEP 9: COUNT DETECTED OBJECTS
# ============================================================

object_count = {}

for box in result.boxes:

    class_id = int(box.cls[0])

    class_name = model.names[class_id]

    if class_name in object_count:

        object_count[class_name] += 1

    else:

        object_count[class_name] = 1


print("\nObject Count:")
print("---------------------------")

for object_name, count in object_count.items():

    print(
        f"{object_name}: {count}"
    )


# ============================================================
# STEP 10: CALCULATE AVERAGE CONFIDENCE
# ============================================================

confidences = []

for box in result.boxes:

    confidence = float(box.conf[0])

    confidences.append(confidence)


if len(confidences) > 0:

    average_confidence = np.mean(confidences)

    print(
        "\nAverage Confidence Score:",
        round(average_confidence, 2)
    )

else:

    average_confidence = 0

    print(
        "\nNo objects detected."
    )


# ============================================================
# STEP 11: SAVE DETECTED IMAGE
# ============================================================

output_path = "detected_objects.jpg"

cv2.imwrite(
    output_path,
    cv2.cvtColor(
        annotated_image,
        cv2.COLOR_RGB2BGR
    )
)

print(
    "\nDetected image saved as:",
    output_path
)


