import tensorflow as tf
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from tensorflow.keras import layers, models
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report
)

print("All libraries imported successfully!")
print("TensorFlow Version:", tf.__version__)


# ============================================================
# STEP 2: LOAD MNIST DATASET
# ============================================================

(x_train, y_train), (x_test, y_test) = tf.keras.datasets.mnist.load_data()

print("\nMNIST Dataset Loaded Successfully!")
print("-----------------------------------")
print("Training Images :", x_train.shape)
print("Training Labels :", y_train.shape)
print("Testing Images  :", x_test.shape)
print("Testing Labels  :", y_test.shape)


# ============================================================
# STEP 3: DISPLAY SAMPLE IMAGES
# ============================================================

plt.figure(figsize=(10, 5))

for i in range(10):
    plt.subplot(2, 5, i + 1)
    plt.imshow(x_train[i], cmap="gray")
    plt.title("Label: " + str(y_train[i]))
    plt.axis("off")

plt.suptitle("Sample MNIST Images")
plt.tight_layout()
plt.show()


# ============================================================
# STEP 4: IMAGE PREPROCESSING
# ============================================================

# Normalize pixel values from 0-255 to 0-1
x_train = x_train.astype("float32") / 255.0
x_test = x_test.astype("float32") / 255.0

# Add channel dimension
# Original: (60000, 28, 28)
# New     : (60000, 28, 28, 1)

x_train = x_train.reshape(-1, 28, 28, 1)
x_test = x_test.reshape(-1, 28, 28, 1)

print("\nAfter Preprocessing:")
print("---------------------------")
print("Training Shape:", x_train.shape)
print("Testing Shape :", x_test.shape)
print("Pixel Range   :", x_train.min(), "to", x_train.max())


# ============================================================
# STEP 5: DESIGN CNN MODEL
# ============================================================

model = models.Sequential([

    # First Convolution Layer
    layers.Conv2D(
        32,
        (3, 3),
        activation="relu",
        input_shape=(28, 28, 1)
    ),

    # First Pooling Layer
    layers.MaxPooling2D((2, 2)),

    # Second Convolution Layer
    layers.Conv2D(
        64,
        (3, 3),
        activation="relu"
    ),

    # Second Pooling Layer
    layers.MaxPooling2D((2, 2)),

    # Convert feature maps into 1D vector
    layers.Flatten(),

    # Fully Connected Layer
    layers.Dense(
        128,
        activation="relu"
    ),

    # Dropout to reduce overfitting
    layers.Dropout(0.5),

    # Output Layer - 10 classes (0 to 9)
    layers.Dense(
        10,
        activation="softmax"
    )
])

print("\nCNN Model Created Successfully!")

model.summary()


# ============================================================
# STEP 6: COMPILE CNN MODEL
# ============================================================

model.compile(
    optimizer="adam",
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

print("\nModel Compiled Successfully!")
print("Optimizer : Adam")
print("Loss      : Sparse Categorical Crossentropy")
print("Metric    : Accuracy")


# ============================================================
# STEP 7: TRAIN CNN MODEL
# ============================================================

print("\nStarting CNN Training...")
print("-----------------------------------")

history = model.fit(
    x_train,
    y_train,
    epochs=5,
    batch_size=64,
    validation_split=0.1,
    verbose=1
)

print("\nCNN Training Completed Successfully!")


# ============================================================
# STEP 8: TRAINING AND VALIDATION ACCURACY
# ============================================================

plt.figure(figsize=(8, 5))

plt.plot(
    history.history["accuracy"],
    label="Training Accuracy"
)

plt.plot(
    history.history["val_accuracy"],
    label="Validation Accuracy"
)

plt.xlabel("Epoch")
plt.ylabel("Accuracy")
plt.title("Training and Validation Accuracy")
plt.legend()
plt.grid(True)
plt.show()


# ============================================================
# STEP 9: TRAINING AND VALIDATION LOSS
# ============================================================

plt.figure(figsize=(8, 5))

plt.plot(
    history.history["loss"],
    label="Training Loss"
)

plt.plot(
    history.history["val_loss"],
    label="Validation Loss"
)

plt.xlabel("Epoch")
plt.ylabel("Loss")
plt.title("Training and Validation Loss")
plt.legend()
plt.grid(True)
plt.show()


# ============================================================
# STEP 10: EVALUATE MODEL ON TEST DATA
# ============================================================

test_loss, test_accuracy = model.evaluate(
    x_test,
    y_test,
    verbose=0
)

print("\n============================================")
print("             MODEL EVALUATION")
print("============================================")
print("Test Loss     :", round(test_loss, 4))
print("Test Accuracy :", round(test_accuracy, 4))
print("Test Accuracy :", round(test_accuracy * 100, 2), "%")


# ============================================================
# STEP 11: MAKE PREDICTIONS
# ============================================================

y_probability = model.predict(
    x_test,
    verbose=0
)

y_pred = np.argmax(
    y_probability,
    axis=1
)

print("\nPredictions Generated Successfully!")


# ============================================================
# STEP 12: CALCULATE PERFORMANCE METRICS
# ============================================================

accuracy = accuracy_score(
    y_test,
    y_pred
)

precision = precision_score(
    y_test,
    y_pred,
    average="weighted",
    zero_division=0
)

recall = recall_score(
    y_test,
    y_pred,
    average="weighted",
    zero_division=0
)

f1 = f1_score(
    y_test,
    y_pred,
    average="weighted",
    zero_division=0
)

print("\n============================================")
print("          PERFORMANCE METRICS")
print("============================================")
print("Accuracy  :", round(accuracy, 4))
print("Precision :", round(precision, 4))
print("Recall    :", round(recall, 4))
print("F1-Score  :", round(f1, 4))


# ============================================================
# STEP 13: CLASSIFICATION REPORT
# ============================================================

print("\n============================================")
print("           CLASSIFICATION REPORT")
print("============================================")

print(
    classification_report(
        y_test,
        y_pred,
        zero_division=0
    )
)


# ============================================================
# STEP 14: CONFUSION MATRIX
# ============================================================

cm = confusion_matrix(
    y_test,
    y_pred
)

plt.figure(figsize=(10, 8))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=range(10),
    yticklabels=range(10)
)

plt.xlabel("Predicted Label")
plt.ylabel("Actual Label")
plt.title("Confusion Matrix - MNIST CNN")
plt.show()


# ============================================================
# STEP 15: PREDICTION ON UNSEEN TEST IMAGES
# ============================================================

plt.figure(figsize=(12, 8))

for i in range(15):

    plt.subplot(3, 5, i + 1)

    plt.imshow(
        x_test[i].reshape(28, 28),
        cmap="gray"
    )

    predicted_label = y_pred[i]
    actual_label = y_test[i]

    plt.title(
        f"Actual: {actual_label}\nPredicted: {predicted_label}"
    )

    plt.axis("off")

plt.suptitle("CNN Predictions on Unseen Test Images")
plt.tight_layout()
plt.show()


# ============================================================
# STEP 16: SHOW INCORRECT PREDICTIONS
# ============================================================

incorrect_indices = np.where(
    y_pred != y_test
)[0]

print("\nTotal Incorrect Predictions:",
      len(incorrect_indices))

plt.figure(figsize=(12, 8))

number_of_images = min(
    10,
    len(incorrect_indices)
)

for i in range(number_of_images):

    index = incorrect_indices[i]

    plt.subplot(2, 5, i + 1)

    plt.imshow(
        x_test[index].reshape(28, 28),
        cmap="gray"
    )

    plt.title(
        f"Actual: {y_test[index]}\n"
        f"Predicted: {y_pred[index]}"
    )

    plt.axis("off")

plt.suptitle("Examples of Misclassified Images")
plt.tight_layout()
plt.show()


# ============================================================
# STEP 17: SAVE TRAINED MODEL
# ============================================================

model.save("mnist_cnn_model.keras")

print("\nTrained CNN model saved successfully!")
print("File Name: mnist_cnn_model.keras")


